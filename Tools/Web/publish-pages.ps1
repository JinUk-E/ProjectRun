param(
    [Parameter(Mandatory=$true)][string]$Tag,
    [Parameter(Mandatory=$true)][string]$ZipPath
)
$ErrorActionPreference = 'Stop'
if ($Tag -notmatch '^web-[A-Za-z0-9][A-Za-z0-9._-]*$') { throw 'Use a web- prefixed release tag, such as web-test-0.1.0.' }
$archive = Get-Item -LiteralPath $ZipPath
if ($archive.Name -notlike 'StarlightWorkshopWeb-*.zip') { throw 'Use an archive generated by package-web.ps1.' }
& gh release create $Tag $archive.FullName --repo JinUk-E/ProjectRun --target main --prerelease --title "Starlight Workshop $Tag" --notes 'Browser playtest build. See DEPLOYMENT.txt and CREDITS.txt in the archive.'
if ($LASTEXITCODE -ne 0) { throw 'Release upload failed. Deployment was not started.' }
& gh workflow run pages.yml --repo JinUk-E/ProjectRun --ref main -f "release_tag=$Tag"
if ($LASTEXITCODE -ne 0) { throw 'Release uploaded, but Pages workflow did not start. Run it from GitHub Actions.' }
Write-Output 'Pages deployment requested. Check GitHub Actions for completion before sharing the URL.'
